def practice_4():
    """실습 4: 중첩 반복문으로 구구단 출력 (원본: day1-4.py)

    핵심: 반복문 안에 반복문을 넣어 두 숫자의 조합을 만듭니다.
          range(2, 10)은 2~9, range(1, 10)은 1~9입니다.
          end="\t"는 줄바꿈 대신 탭을 넣습니다.
          print()는 다음 줄로 넘어갑니다.
    확인 결과: 2단부터 9단까지 각각 1~9를 곱한 결과 출력
    추가 연습:
        - 3단부터 7단까지만 출력해 보세요.
        - 두 반복문의 순서를 바꾸어 출력 배치를 비교해 보세요.

    원본은 전체가 삼중 따옴표로 묶여 실행되지 않았습니다.
    여기서는 실행 가능한 코드로 정리하고, 곱셈을 dan * i로 통일했습니다.
    """
    for dan in range(2, 10):
        for i in range(1, 10):
            print(f"{dan} x {i} = {dan * i}", end="\t")
        print()
