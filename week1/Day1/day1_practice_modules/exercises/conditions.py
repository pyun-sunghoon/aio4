def practice_2():
    """실습 2: 입력과 조건문 (원본: day1-2.py)

    핵심: input()은 문자열을 반환하므로 int()로 정수로 바꿉니다.
          if/else로 조건에 따라 실행할 코드를 선택합니다.
    확인 입력: 59 → 불합격, 60 → 합격, 100 → 합격
    추가 연습:
        - 합격 기준을 70점으로 바꾸어 보세요.
        - elif를 사용해 90점 이상 '우수', 60점 이상 '합격',
          그 외 '불합격'으로 나누어 보세요.
    """
    score = int(input("점수를 입력하세요 : "))
    if score >= 60:
        print("합격")
    else:
        print("불합격")
